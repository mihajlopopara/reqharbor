// fuzzCorpus reads testdata/fuzz/FuzzCanonicalize (the `go test fuzz v1` format).
func fuzzCorpus(t *testing.T) [][2]string {
	dir := filepath.Join("testdata", "fuzz", "FuzzCanonicalize")
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		t.Fatal(err)
	}
	var out [][2]string
	for _, e := range entries {
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		lines := strings.Split(strings.TrimSpace(string(b)), "\n")
		if len(lines) != 2 || lines[0] != "go test fuzz v1" || !strings.HasPrefix(lines[1], "[]byte(") || !strings.HasSuffix(lines[1], ")") {
			t.Fatalf("%s: unexpected corpus format", e.Name())
		}
		s, err := strconv.Unquote(strings.TrimSuffix(strings.TrimPrefix(lines[1], "[]byte("), ")"))
		if err != nil {
			t.Fatalf("%s: %v", e.Name(), err)
		}
		if !isUTF8JSONText(s) {
			continue // the fixture is JSON text; byte-level corpus entries stay Go-only
		}
		out = append(out, [2]string{"fuzz corpus " + e.Name(), s})
	}
	sort.Slice(out, func(i, j int) bool { return out[i][0] < out[j][0] })
	return out
}

func isUTF8JSONText(s string) bool { return strings.ToValidUTF8(s, "") == s }

func buildParity(t *testing.T) []byte {
	var cases []parityCase
	for _, e := range append(parityEdges(), fuzzCorpus(t)...) {
		c := parityCase{Name: e[0], Input: e[1]}
		out, err := Canonicalize([]byte(e[1]))
		if err == nil {
			s := string(out)
			c.Accepted, c.Output = true, &s
		} else {
			c.Reason = reasonOf(err)
		}
		cases = append(cases, c)
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(struct {
		Comment string       `json:"comment"`
		Cases   []parityCase `json:"cases"`
	}{"Generated by server/internal/jsonx/serde_parity_test.go (go test ./internal/jsonx -run SerdeParity -update). Checked by crates/core/tests/serde_parity.rs.", cases}); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}

func TestSerdeParityFixture(t *testing.T) {
	want := buildParity(t)
	if *update {
		if err := os.WriteFile(parityFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(parityFile)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/jsonx -run SerdeParity -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; run go test ./internal/jsonx -run SerdeParity -update", parityFile)
	}
	// Spot-check the expectations the design names.
	var f struct{ Cases []parityCase }
	if err := json.Unmarshal(got, &f); err != nil {
		t.Fatal(err)
	}
	byName := map[string]parityCase{}
	for _, c := range f.Cases {
		byName[c.Name] = c
	}
	for name, reason := range map[string]string{
		"overflow": "number_range", "negative overflow": "number_range", "just above f64 max": "number_range",
		"400-digit integer": "number_range", "lone high surrogate": "lone_surrogate", "lone low surrogate": "lone_surrogate",
		"lone surrogate in key": "lone_surrogate", "depth 101": "too_deep", "array depth 101": "too_deep",
	} {
		if c := byName[name]; c.Accepted || c.Reason != reason {
			t.Errorf("%s: %+v, want refused %s", name, c, reason)
		}
	}
	for _, name := range []string{"max finite exponent", "underflow to zero", "u64 max plus one", "paired surrogates", "max code point raw", "depth 100", "array depth 100"} {
		if !byName[name].Accepted {
			t.Errorf("%s refused", name)
		}
	}
}
