package jsonx

// Serde parity (06-go-server.md §1.6): this test writes testdata/serde_parity.json from a
// hand-written edge list plus the saved FuzzCanonicalize corpus. The Rust test
// crates/core/tests/serde_parity.rs reads the same file and checks that every accepted output
// parses as the client's PullPage, and that every input refused for number range or a lone
// surrogate is refused by serde_json too.
//
//   docker compose run --rm go go test ./internal/jsonx -run SerdeParity -update

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite testdata/serde_parity.json")

const parityFile = "testdata/serde_parity.json"

type parityCase struct {
	Name     string  `json:"name"`
	Input    string  `json:"input"`
	Accepted bool    `json:"accepted"`
	Output   *string `json:"output,omitempty"`
	Reason   string  `json:"reason,omitempty"`
}

func reasonOf(err error) string {
	switch {
	case errors.Is(err, ErrNumberRange):
		return "number_range"
	case errors.Is(err, ErrLoneSurrogate):
		return "lone_surrogate"
	case errors.Is(err, ErrTooDeep):
		return "too_deep"
	default:
		return "syntax"
	}
}

